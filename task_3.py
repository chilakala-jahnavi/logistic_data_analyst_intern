import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

np.random.seed(42)
sns.set_theme(style="whitegrid", palette="deep")

# ---------- 1. SIMULATE DATASET ----------
n = 1000
hubs = ["Hub_North", "Hub_South", "Hub_East", "Hub_West", "Hub_Central"]
carriers = ["Carrier_A", "Carrier_B", "Carrier_C", "Carrier_D"]
modes = ["Road", "Rail", "Air", "Sea"]

df = pd.DataFrame({
    "Shipment_ID": [f"SHP{1000+i}" for i in range(n)],
    "Date": pd.date_range("2024-01-01", periods=n, freq="8h"),
    "Origin": np.random.choice(hubs, n),
    "Destination": np.random.choice(hubs, n),
    "Carrier": np.random.choice(carriers, n),
    "Transport_Mode": np.random.choice(modes, n, p=[0.55, 0.20, 0.15, 0.10]),
    "Distance_km": np.random.uniform(50, 2500, n),
    "Shipment_Weight_kg": np.random.uniform(10, 5000, n),
    "Shipment_Volume_m3": np.random.uniform(0.1, 40, n),
})

# mode speed multipliers (days per 100 km) and cost multipliers ($ per km)
speed = {"Road": 0.10, "Rail": 0.13, "Air": 0.03, "Sea": 0.20}
cost_per_km = {"Road": 1.2, "Rail": 0.9, "Air": 6.0, "Sea": 0.6}
carrier_delay = {"Carrier_A": 0, "Carrier_B": 0.4, "Carrier_C": 0.9, "Carrier_D": -0.3}

df["Promised_Time_Days"] = np.ceil(df["Distance_km"] * df["Transport_Mode"].map(speed)) + 1

base_time = df["Distance_km"] * df["Transport_Mode"].map(speed)
noise = np.random.normal(0, 0.6, n)
extra = df["Carrier"].map(carrier_delay) * np.random.uniform(0.3, 1.2, n)
df["Delivery_Time_Days"] = np.maximum(0.5, base_time + noise + extra).round(2)

df["On_Time"] = df["Delivery_Time_Days"] <= df["Promised_Time_Days"]

df["Fuel_Cost_USD"] = (df["Distance_km"] * df["Transport_Mode"].map(cost_per_km) * 0.35
                       + df["Shipment_Weight_kg"] * 0.05).round(2)
df["Transportation_Cost_USD"] = (df["Distance_km"] * df["Transport_Mode"].map(cost_per_km)
                                 + df["Shipment_Weight_kg"] * 0.15
                                 + df["Shipment_Volume_m3"] * 8
                                 + np.random.normal(0, 50, n)).round(2)
df["Transportation_Cost_USD"] = df["Transportation_Cost_USD"].clip(lower=20)

# Delay reason only for late shipments
late = ~df["On_Time"]
reasons = ["Weather", "Customs", "Traffic", "Carrier Issue"]
df["Delay_Reason"] = "None"
df.loc[late, "Delay_Reason"] = np.random.choice(reasons, late.sum(), p=[0.25, 0.20, 0.35, 0.20])

df["Customer_Rating"] = np.clip(
    np.where(df["On_Time"], np.random.normal(4.3, 0.5, n), np.random.normal(2.8, 0.8, n)),
    1, 5).round(1)

df.to_csv("logistics_dataset.csv", index=False)

# ---------- 2. EDA ----------
print("Shape:", df.shape)
print(df.describe(include="all").T)
print("\nMissing values:\n", df.isna().sum())

numeric_cols = ["Distance_km", "Shipment_Weight_kg", "Shipment_Volume_m3",
                "Delivery_Time_Days", "Promised_Time_Days",
                "Transportation_Cost_USD", "Fuel_Cost_USD", "Customer_Rating"]
print("\nCorrelation matrix:\n", df[numeric_cols].corr().round(2))

# central tendency table
ct = df[numeric_cols].agg(["mean", "median", "std", "skew"]).T
print("\nCentral tendency:\n", ct.round(2))

# ---------- 3. VISUALIZATIONS ----------
# Fig 1 — Distribution of delivery times + cost
fig, ax = plt.subplots(1, 2, figsize=(14, 5))
sns.histplot(df["Delivery_Time_Days"], kde=True, ax=ax[0], color="steelblue")
ax[0].set_title("Fig 1a: Distribution of Delivery Times")
ax[0].set_xlabel("Delivery Time (days)")
sns.histplot(df["Transportation_Cost_USD"], kde=True, ax=ax[1], color="darkorange")
ax[1].set_title("Fig 1b: Distribution of Transportation Cost")
ax[1].set_xlabel("Cost (USD)")
plt.tight_layout(); plt.savefig("fig1_distributions.png", dpi=150); plt.close()

# Fig 2 — Cost vs Distance by Mode (scatter)
plt.figure(figsize=(10, 6))
sns.scatterplot(data=df, x="Distance_km", y="Transportation_Cost_USD",
                hue="Transport_Mode", alpha=0.7)
plt.title("Fig 2: Cost vs Distance by Transport Mode")
plt.savefig("fig2_cost_distance.png", dpi=150); plt.close()

# Fig 3 — Delivery time by carrier (boxplot)
plt.figure(figsize=(9, 5))
sns.boxplot(data=df, x="Carrier", y="Delivery_Time_Days", hue="Carrier", legend=False)
plt.title("Fig 3: Delivery Time Distribution by Carrier")
plt.savefig("fig3_carrier_box.png", dpi=150); plt.close()

# Fig 4 — Correlation heatmap
plt.figure(figsize=(10, 7))
sns.heatmap(df[numeric_cols].corr(), annot=True, fmt=".2f", cmap="coolwarm", center=0)
plt.title("Fig 4: Correlation Heatmap of Key Variables")
plt.savefig("fig4_corr.png", dpi=150); plt.close()

# Fig 5 — On-time rate by mode (bar)
plt.figure(figsize=(8, 5))
ot = df.groupby("Transport_Mode")["On_Time"].mean().sort_values() * 100
sns.barplot(x=ot.index, y=ot.values, hue=ot.index, legend=False, palette="viridis")
plt.ylabel("On-Time Rate (%)"); plt.title("Fig 5: On-Time Delivery Rate by Mode")
plt.savefig("fig5_ontime_mode.png", dpi=150); plt.close()

# Fig 6 — Delay reasons (count)
plt.figure(figsize=(8, 5))
sns.countplot(data=df[df["Delay_Reason"] != "None"], x="Delay_Reason",
              order=df["Delay_Reason"].value_counts().index, hue="Delay_Reason", legend=False)
plt.title("Fig 6: Frequency of Delay Reasons")
plt.savefig("fig6_delay_reasons.png", dpi=150); plt.close()

# Fig 7 — Monthly trend: avg cost & on-time rate (dual axis)
monthly = df.set_index("Date").resample("ME").agg(
    avg_cost=("Transportation_Cost_USD", "mean"),
    ontime=("On_Time", "mean"))
fig, ax1 = plt.subplots(figsize=(11, 5))
ax1.plot(monthly.index, monthly["avg_cost"], marker="o", color="tab:red")
ax1.set_ylabel("Avg Cost (USD)", color="tab:red")
ax2 = ax1.twinx()
ax2.plot(monthly.index, monthly["ontime"] * 100, marker="s", color="tab:blue")
ax2.set_ylabel("On-Time Rate (%)", color="tab:blue")
plt.title("Fig 7: Monthly Trend of Average Cost and On-Time Rate")
plt.savefig("fig7_trend.png", dpi=150); plt.close()

# Fig 8 — Fuel share of total cost by mode (stacked)
fuel_share = df.groupby("Transport_Mode").agg(
    fuel=("Fuel_Cost_USD", "sum"),
    total=("Transportation_Cost_USD", "sum"))
fuel_share["non_fuel"] = fuel_share["total"] - fuel_share["fuel"]
fuel_share[["fuel", "non_fuel"]].plot(kind="bar", stacked=True, figsize=(9, 5))
plt.title("Fig 8: Fuel vs Non-Fuel Cost by Transport Mode")
plt.ylabel("Total Cost (USD)")
plt.savefig("fig8_fuel_stack.png", dpi=150); plt.close()

