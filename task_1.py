import numpy as np
import pandas as pd

rng = np.random.default_rng(42)

# ---------------------------------------------------------------
# 1. Build a synthetic product master
# ---------------------------------------------------------------
n_skus = 120
sku_ids = [f"SKU_{i:04d}" for i in range(1, n_skus + 1)]

product_master = pd.DataFrame({
    "sku_id": sku_ids,
    # Pareto-ish value distribution: a few expensive, many cheap
    "unit_cost": np.round(rng.lognormal(mean=2.5, sigma=1.0, size=n_skus), 2),
    # Lead times between 2 and 21 days
    "lead_time_days": rng.integers(2, 22, size=n_skus),
})

# ---------------------------------------------------------------
# 2. Simulate 24 months of daily order lines per SKU
# ---------------------------------------------------------------
dates = pd.date_range("2023-01-01", "2024-12-31", freq="D")

rows = []
for _, prod in product_master.iterrows():
    sku = prod["sku_id"]
    # Give each SKU its own baseline demand and seasonality shape
    base = rng.uniform(5, 200)                 # mean daily units
    weekly_amp = rng.uniform(0, 0.4) * base    # weekend dip amplitude
    annual_amp = rng.uniform(0, 0.3) * base    # yearly cycle

    for d in dates:
        # Weekend effect (lower demand Sat/Sun)
        dow_factor = 1 - weekly_amp / base if d.dayofweek >= 5 else 1.0
        # Annual sinusoid
        annual = annual_amp * np.sin(2 * np.pi * d.dayofyear / 365)
        # Random noise (Poisson-like)
        lam = max(base * dow_factor + annual, 0.1)
        qty_ordered = rng.poisson(lam)

        if qty_ordered == 0:
            continue  # no order line that day

        # Simulate occasional stockouts: fulfilled < ordered
        if rng.random() < 0.05:
            qty_shipped = rng.integers(0, qty_ordered)  # partial / zero fill
        else:
            qty_shipped = qty_ordered

        rows.append((sku, d, qty_ordered, qty_shipped))

orders = pd.DataFrame(rows, columns=["sku_id", "order_date", "qty_ordered", "qty_shipped"])

# Attach unit cost so downstream value-based ABC works
orders = orders.merge(product_master[["sku_id", "unit_cost"]], on="sku_id", how="left")

# ---------------------------------------------------------------
# 3. Persist to CSV so the original pd.read_csv line works
# ---------------------------------------------------------------
orders.to_csv("order_lines.csv", index=False)
print(f"Wrote order_lines.csv with {len(orders):,} rows for {orders['sku_id'].nunique()} SKUs")

# ---------------------------------------------------------------
# 4. Original loading step — now succeeds unchanged
# ---------------------------------------------------------------
orders = pd.read_csv("order_lines.csv", parse_dates=["order_date"])

# Aggregate to daily SKU demand
daily = (orders
    .groupby(["sku_id", "order_date"])
    .agg(
        qty_demanded=("qty_ordered", "sum"),
        qty_fulfilled=("qty_shipped", "sum"),
        stockout_flag=("qty_shipped", lambda x: (x == 0).any()),
        unit_cost=("unit_cost", "first"),
    )
    .reset_index()
)

# Correct censored demand: where stockout occurred, replace observed with
# a proxy = historical average demand for that SKU on comparable days
sku_avg = daily[~daily["stockout_flag"]].groupby("sku_id")["qty_demanded"].mean()
daily.loc[daily["stockout_flag"], "qty_demanded_corrected"] = (
    daily.loc[daily["stockout_flag"], "sku_id"].map(sku_avg)
)
daily["qty_demanded_corrected"] = daily["qty_demanded_corrected"].fillna(daily["qty_demanded"])